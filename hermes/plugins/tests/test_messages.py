def test_levels_are_the_notify_contracts():
    levels = {k: v for k, v in NOTIFY["levels"].items() if not k.startswith("$")}
    assert _messages.LEVEL_STATE == {k: v["state"] for k, v in levels.items()}
    templates = {k: v for k, v in NOTIFY["templates"].items() if not k.startswith("$")}
    for name, level in _messages.TEMPLATE_LEVEL.items():
        assert name in templates, f"{name} is not a template the contract names"
        assert templates[name]["level"] == level, name


def test_each_level_carries_its_states_glyph():
    for level, state in _messages.LEVEL_STATE.items():
        assert _messages.glyph(level) == _glyphs.STATES[state]["glyph"], level
    assert _messages.glyph("no such level") == _glyphs.STATES["idle"]["glyph"]
    # Needs-you and failed are told apart at a glance.
    assert _messages.glyph("attention") != _messages.glyph("danger")


# --- the templates --------------------------------------------------------------------------

RENDERED = {
    "alert": _messages.alert("GPU 0 temperature is 84.2 °C, above the 80.0 °C limit (14:30)."),
    "alert-still": _messages.alert("GPU 0 temperature is still 84.2 °C, over the 80.0 °C limit (15:30)."),
    "recovered": _messages.recovered("GPU 0 temperature is back to 77.5 °C, under 78.0 °C (16:00)."),
    "recovered-telemetry": _messages.recovered("GPU watchdog: telemetry is back (16:05)."),
    "blind": _messages.blind("the telemetry read failed", "03:15", "Check Grafana and the exporter."),
    "goal-set": _messages.goal("set", "Goal set (20-turn budget): keep the study at 21° until 22h"),
    "goal-parked": _messages.goal("parked", "Goal parked on pid 4242: keep the study at 21° until 22h"),
    "goal-continuing": _messages.goal("continuing", "Goal continues."),
    "approval": _messages.approval("ha_call_service", "acts on the house",
                                   "domain: lock, service: unlock, entity_id: lock.front_door"),
    "approval-bare": _messages.approval("terminal", "can change the host"),
    "approval-clipped": _messages.approval("write_file", "writes outside the sandbox", "path: /etc/hosts, content: 127.0.0.1 …"),
}


def test_an_alert_wears_the_alert_glyph_and_a_recovery_the_steady_ring():
    alert = _glyphs.STATES["alert"]["glyph"]
    idle = _glyphs.STATES["idle"]["glyph"]
    assert RENDERED["alert"].startswith(alert + " GPU 0 temperature is 84.2 °C, above the 80.0 °C limit")
    assert RENDERED["alert-still"].startswith(alert + " ")
    assert RENDERED["recovered"].startswith(idle + " GPU 0 temperature is back to 77.5 °C")
    assert RENDERED["recovered-telemetry"].startswith(idle + " GPU watchdog: telemetry is back")


def test_a_blind_watchdog_needs_the_person_and_says_what_to_do():
    attention = _glyphs.STATES["attention"]["glyph"]
    line = RENDERED["blind"]
    assert line.startswith(attention + " GPU watchdog: no readings, the telemetry read failed (03:15).")
    assert line.endswith("Nothing is being watched until it comes back. Check Grafana and the exporter.")


def test_goal_lines_use_the_reactors_goal_glyph_and_hermes_lifecycle_glyphs():
    assert RENDERED["goal-set"].startswith(_glyphs.STATES["goal"]["glyph"] + " Goal set")
    assert RENDERED["goal-parked"].startswith(_messages.GOAL_GLYPHS["parked"] + " Goal parked")
    assert RENDERED["goal-continuing"] == _messages.GOAL_GLYPHS["continuing"] + " Goal continues."
    with pytest.raises(ValueError):
        _messages.goal("exploded", "no")


def test_goal_glyphs_are_the_installed_hermes_own():
    """Hermes' loop prints its status line in the same chat; two vocabularies for one goal is drift."""
    root = _hermes_root()
    if root is None:
        pytest.skip("no Hermes install beside this checkout")
    source = (root / "hermes_cli" / "goals.py").read_text(encoding="utf-8")
    for event, glyph in _messages.GOAL_GLYPHS.items():
        if event == "set":
            # `set` is the reactor's own goal mark, and it is also what Hermes prints for an active goal.
            assert f"{glyph} Goal (active" in source
            continue
        assert glyph in source, f"Hermes never prints {glyph!r} ({event})"
    assert f"{_messages.GOAL_GLYPHS['continuing']} Continuing toward goal" in source
    assert f"{_messages.GOAL_GLYPHS['parked']} Goal parked" in source
    assert f"{_messages.GOAL_GLYPHS['done']} Goal achieved" in source


def test_the_approval_reason_names_the_rule_then_the_arguments_as_sentences():
    assert RENDERED["approval"] == (
        "ha_call_service acts on the house. domain: lock, service: unlock, entity_id: lock.front_door.")
    assert RENDERED["approval-bare"] == "terminal can change the host."
    # A clipped summary keeps its ellipsis and gains no stray full stop.
    assert RENDERED["approval-clipped"].endswith("content: 127.0.0.1 …")
    # No glyph: Hermes' card owns the header, and ours would land after "Reason:".
    for state in _glyphs.STATES.values():
        assert not RENDERED["approval"].startswith(state["glyph"])


@pytest.mark.parametrize("name", sorted(RENDERED))
def test_every_template_keeps_the_copy_rules(name):
    text = RENDERED[name]
    assert " — " not in text and " · " not in text, "meta is a sentence, not a joined half-sentence (§11)"
    assert "\n" not in text or name.startswith("goal"), "one line per delivery"
    assert not text.endswith(" ")
    assert "!" not in text, "no exclamation marks in system copy (§11)"


@pytest.mark.parametrize("name", sorted(RENDERED))
def test_every_template_survives_the_markdownv2_wire(name):
    """Escaped as Hermes escapes it, read back as the fake reads it: the same sentence, glyph intact."""
    text = RENDERED[name]
    wire = _escape_like_hermes(text)
    assert unescape_markdown_v2(wire) == text
    # Nothing in a template is markup Hermes would convert before escaping:
    # a bare pair of `*` or `_` becomes bold or italic, a leading `#` a header.
    assert not re.search(r"\*[^*]+\*|(?<!\w)_[^_]+_(?!\w)|~~|\|\||^#|^>", text, re.M)
    # Every glyph is outside MarkdownV2's reserved set, so it reaches the wire as itself.
    glyph = text.split(" ", 1)[0]
    if name.startswith(("alert", "recovered", "blind", "goal")):
        assert glyph not in MARKDOWN_V2_RESERVED
        assert wire.startswith(glyph + " ")
