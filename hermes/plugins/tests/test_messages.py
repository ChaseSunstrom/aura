"""The chat-platform templates echo the HUD: the glyphs are the reactor's, and a line survives the wire.

Three tables are held together here. ``_glyphs.py`` is generated by ``design/build.py`` from
the one glyph table the console theme is generated from, so it is checked against
``design/generated/console-theme.json`` (the same table, through the other emitter) and
``tests/contracts/reactor.json`` (the words and the precedence). ``_messages.py``'s level
table is checked against ``tests/contracts/notify.json``, which the web's ``notices.ts`` and
the phone read too. And the goal lifecycle glyphs are checked against the installed Hermes,
whose loop prints its status line beside ours.

The last thing is the wire. Hermes sends a delivery as Telegram MarkdownV2 — ``84.2`` leaves
as ``84\\.2`` — and the phase6 delivery proof was red for a day because the test polled for
the sentence a person reads. So every template is rendered and escaped the way Hermes
escapes it (the real ``_escape_mdv2`` when Hermes is installed, the fake's reserved set
otherwise) and must come back through the fake's ``unescape_markdown_v2`` unchanged, with the
glyph intact: a glyph that Telegram treated as markup would be a message that never arrived.

Not covered: what Hermes' ``format_message`` does with markdown a MODEL writes (the briefs);
those are not templates and carry no glyph on purpose.
"""
from __future__ import annotations

import importlib
import json
import os
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(ROOT))
from _shared import _glyphs, _messages  # noqa: E402
from bench.fixtures.telegram_fake import MARKDOWN_V2_RESERVED, unescape_markdown_v2  # noqa: E402

THEME = json.loads((ROOT / "design/generated/console-theme.json").read_text(encoding="utf-8"))
REACTOR = json.loads((ROOT / "tests/contracts/reactor.json").read_text(encoding="utf-8"))
NOTIFY = json.loads((ROOT / "tests/contracts/notify.json").read_text(encoding="utf-8"))


def _hermes_root() -> Path | None:
    home = Path(os.environ.get("HERMES_HOME", str(Path.home() / ".hermes")))
    for candidate in (Path(os.environ.get("HERMES_INSTALL_DIR", "")), home / "hermes-agent"):
        if candidate.name and (candidate / "hermes_cli" / "goals.py").is_file():
            return candidate
    return None


def _escape_like_hermes(text: str) -> str:
    """Hermes' own MarkdownV2 escaper when it is installed; the documented reserved set otherwise."""
    root = _hermes_root()
    if root is not None:
        if str(root) not in sys.path:
            sys.path.append(str(root))
        try:
            adapter = importlib.import_module("plugins.platforms.telegram.adapter")
            return adapter._escape_mdv2(text)
        except Exception:  # noqa: BLE001 — a Hermes without the adapter falls back below
            pass
    return re.sub("([" + re.escape(MARKDOWN_V2_RESERVED) + "\\\\])", r"\\\1", text)


# --- the generated table ------------------------------------------------------------------


def test_the_generated_glyphs_are_the_console_themes():
    """One table, two emitters: a glyph that differed here would differ on Telegram."""
    states = THEME["reactor"]["states"]
    assert set(_glyphs.STATES) == set(states)
    for name, entry in states.items():
        ours = _glyphs.STATES[name]
        assert ours["glyph"] == entry["glyph"], name
        assert ours["ascii"] == entry["ascii"], name
        assert ours["meaning"] == entry["meaning"], name
        assert ours["color"] == THEME["palette"][entry["color"]]["hex"], name


def test_the_generated_words_and_precedence_are_the_contracts():
    for name, entry in REACTOR["states"].items():
        assert _glyphs.STATES[name]["word"] == entry["word"], name
    assert list(_glyphs.PRECEDENCE) == REACTOR["precedence"]
    assert "goal" not in _glyphs.PRECEDENCE, "the overlay cannot win"


def test_the_generated_module_is_current():
    """`design/build.py --check` is the gate; this is the same check where the reader lives."""
    sys.path.insert(0, str(ROOT / "design"))
    build = importlib.import_module("build")
    tokens = build.load()
    expected = build.gen_plugin_glyphs(tokens)
    actual = (ROOT / "hermes/plugins/_shared/_glyphs.py").read_text(encoding="utf-8")
    assert actual == expected, "stale: run python3 design/build.py"


