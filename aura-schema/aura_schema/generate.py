"""Render the files that must not drift from :mod:`aura_schema.settings`.

One schema, three generated outputs (``make schema`` writes them; a CI job runs
this with ``--check`` and fails if any is stale — the same generate-and-check
contract ``design/build.py`` uses for the design tokens):

* ``deploy/config.template.yaml`` — the Hermes config the entrypoint renders on
  first start. The layout (comments, non-setting structure) is the checked-in
  ``templates/config.template.yaml.in``; every ``@key@`` token in it is resolved
  to the setting's ``${ENV_NAME}`` placeholder from the schema, and every
  ``${VAR}`` in the result is checked to be a setting the schema declares — an
  unknown placeholder is an error, not a silently-empty render.
* ``tests/contracts/hermes-settings.json`` — the ``jsettings`` allow-list the
  plugin and the console/Android settings screens read. Its ``keys`` are the
  ``settable`` settings (the eight original runtime keys, type/bounds/doc
  unchanged, plus the D30 HUD keys); it carries the ``groups`` (id, title,
  description, in display order), the ``widgets`` vocabulary, a ``settings``
  catalogue so the surfaces can render every group, and ``hud`` — the surfaces,
  modes and the JSON Schema of a layout document with worked examples, so the
  web, Android and console window managers validate the same shape.
* ``docs/reference/settings.md`` — the human reference, one table per group.

Run ``python -m aura_schema.generate`` to write, ``--check`` to verify.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Callable
from pathlib import Path

from .settings import (
    AUDIT_LOG,
    COMMAND_NAME,
    GROUP_DESCRIPTIONS,
    HUD_ACTIVITIES,
    HUD_MODES,
    SETTINGS,
    SETTINGS_BY_ENV,
    SETTINGS_BY_KEY,
    SURFACES,
    TOOLS,
    TRI_STATES,
    Group,
    LayoutDocument,
    Setting,
    Widget,
    applies,
    settable_settings,
)

#: Repo root — three parents up from ``aura-schema/aura_schema/generate.py``.
ROOT = Path(__file__).resolve().parents[2]
TEMPLATE_IN = Path(__file__).resolve().parent / "templates" / "config.template.yaml.in"

CONFIG_TEMPLATE = ROOT / "deploy" / "config.template.yaml"
CONTRACT = ROOT / "tests" / "contracts" / "hermes-settings.json"
#: The same contract inside the web package. The console imports the catalogue at build
#: time, and the web image is built from jarvis-web/ alone (its Docker context), so an
#: import that reaches up to tests/contracts/ builds on a checkout and fails in the
#: image: pipeline 144, build:web, "Could not resolve ../../../../../tests/contracts/
#: hermes-settings.json". One source, two generated copies, --check guarding both —
#: the pattern the console theme already uses (design/build.py).
WEB_CONTRACT = ROOT / "jarvis-web" / "src" / "lib" / "hud" / "data" / "hermes-settings.json"
SETTINGS_DOC = ROOT / "docs" / "reference" / "settings.md"

_TOKEN_RE = re.compile(r"@([a-z0-9_.]+)@")
_PLACEHOLDER_RE = re.compile(r"\$\{([A-Z0-9_]+)\}")

MARK = "@generated by aura-schema (make schema); edit aura-schema/, not this file"


class GenerationError(ValueError):
    """A token or placeholder that the schema does not back — a fail-fast stop."""


# --------------------------------------------------------------------------- #
# deploy/config.template.yaml
# --------------------------------------------------------------------------- #
def render_config_template() -> str:
    """The Hermes config template, resolved from the schema.

    Each ``@key@`` in the ``.in`` layout becomes the setting's ``${ENV}``
    placeholder; a key that is unknown or has no environment variable is a
    :class:`GenerationError`. The rendered text is then re-scanned and every
    ``${VAR}`` is required to name a setting the schema declares.
    """
    layout = TEMPLATE_IN.read_text(encoding="utf-8")

    def _resolve(match: re.Match[str]) -> str:
        key = match.group(1)
        setting = _by_key(key)
        if setting is None:
            raise GenerationError(f"config template references unknown setting {key!r}")
        if not setting.env:
            raise GenerationError(f"config template setting {key!r} has no .env variable to render")
        return "${" + setting.env + "}"

    rendered = _TOKEN_RE.sub(_resolve, layout)

    leftover = _TOKEN_RE.findall(rendered)
    if leftover:
        raise GenerationError(f"unresolved @token@ in config template: {sorted(set(leftover))}")
    for var in _PLACEHOLDER_RE.findall(rendered):
        if var not in SETTINGS_BY_ENV:
            raise GenerationError(f"config template renders ${{{var}}} but no setting declares it")
    return rendered


def _by_key(key: str) -> Setting | None:
    return SETTINGS_BY_KEY.get(key)


# --------------------------------------------------------------------------- #
# tests/contracts/hermes-settings.json
# --------------------------------------------------------------------------- #
def render_contract() -> str:
    """The ``jsettings`` allow-list + the UI catalogue, as pretty JSON."""
    keys: dict[str, dict[str, object]] = {}
    for s in settable_settings():
        entry: dict[str, object] = {"type": s.contract_type}
        if s.contract_type == "int":
            entry["min"] = s.min
            entry["max"] = s.max
        if s.contract_type == "enum":
            entry["values"] = list(s.choices or ())
        if s.contract_type == "object":
            entry["shape"] = s.shape
        entry["restart_needed"] = s.restart_needed
        entry["doc"] = s.description
        # UI hints the surfaces render from; the plugin's contract test ignores
        # these extra fields (it only checks type/bounds/values/restart/doc).
        entry["group"] = s.group.value
        entry["widget"] = s.widget.value
        keys[s.key] = entry

    contract = {
        "_comment": (
            "Keys the jarvis-settings plugin may read and write on behalf of the apps and "
            "the agent, plus the settings catalogue the console and Android screens render "
            "from. GENERATED from aura-schema (make schema) — edit aura-schema/, not this file."
        ),
        "command": {
            "name": COMMAND_NAME,
            "get": "@<sid> get <key>",
            "set": "@<sid> set <key> <json>",
            "list": "@<sid> list",
            # The propose/apply step (ADR-0044): a `set` the approval matrix would ask
            # about answers {"status":"proposed"} and is written by `apply`.
            "apply": "@<sid> apply <id>",
            "discard": "@<sid> discard <id>",
            "proposals": "@<sid> proposals",
            # What was changed and the way back (T-0700): `history` reads the audit log,
            # `undo` restores a key's last value, the newest change when no key is named.
            "history": "@<sid> history [n]",
            "undo": "@<sid> undo [key]",
        },
        "tools": list(TOOLS),
        "audit_log": AUDIT_LOG,
        "groups": [
            {"id": g.value, "title": g.value, "description": GROUP_DESCRIPTIONS[g]} for g in Group
        ],
        "widgets": [w.value for w in Widget],
        "keys": keys,
        "settings": [_catalog_entry(s) for s in SETTINGS],
        "hud": _hud_section(),
    }
    return json.dumps(contract, indent=2, ensure_ascii=False) + "\n"


#: A layout every surface must accept, and two every surface must refuse — the
#: window managers' unit tests read these so "valid" means the same thing on the
#: web, on Android and on the console.
HUD_LAYOUT_EXAMPLES: dict[str, list[dict[str, object]]] = {
    "valid": [
        {"mode": "task",
         "tree": {"split": "row", "ratio": 0.6, "children": ["chat", {"split": "column", "children": ["goals", "timeline"]}]},
         "panels": [{"id": "chat", "type": "chat"}, {"id": "goals", "type": "goals", "pinned": True},
                    {"id": "timeline", "type": "tool_timeline"}]},
        {"mode": "overview", "tree": None,
         "panels": [{"id": "viewer", "type": "image_viewer", "rect": {"x": 0.5, "y": 0.1, "w": 0.45, "h": 0.6}}]},
        {"mode": "ambient", "tree": None, "panels": []},
    ],
    "invalid": [
        # a leaf that names no panel
        {"mode": "task", "tree": "chat", "panels": []},
        # a mode outside the four
        {"mode": "grid", "tree": None, "panels": []},
        # a duplicate panel id
        {"mode": "focus", "tree": "chat",
         "panels": [{"id": "chat", "type": "chat"}, {"id": "chat", "type": "chat"}]},
        # an unknown field on a panel
        {"mode": "task", "tree": "chat", "panels": [{"id": "chat", "type": "chat", "colour": "red"}]},
    ],
}


def _hud_section() -> dict[str, object]:
    """The D30 layout vocabulary and the layout document's JSON Schema.

    The schema is what :class:`LayoutDocument` validates; the examples are checked
    against it by the schema's own tests, so a surface that implements the schema
    and passes the examples agrees with the plugin.
    """
    return {
        "surfaces": list(SURFACES),
        "modes": list(HUD_MODES),
        "tri_state": list(TRI_STATES),
        "activities": list(HUD_ACTIVITIES),
        "layouts_key": "hud.layouts",
        "layouts_shape": "surface -> activity -> layout_document",
        "layout_document": LayoutDocument.model_json_schema(),
        "examples": HUD_LAYOUT_EXAMPLES,
    }


def _catalog_entry(s: Setting) -> dict[str, object]:
    """One setting as the surfaces see it — a widget hint, not a value.

    A secret's ``default`` is never emitted (it is the empty name-and-shape only);
    non-secret defaults are, so a UI can show what the shipped value would be.
    """
    entry: dict[str, object] = {
        "key": s.key,
        "type": s.contract_type,
        "group": s.group.value,
        "widget": s.widget.value,
        "description": s.description,
        "secret": s.secret,
        "restart_needed": s.restart_needed,
        "settable": s.settable,
        "advanced": s.advanced,
        # Which tier the settings UI draws this row in (ADR-0035). Emitted for
        # every row so a surface never has to guess, and so a new setting cannot
        # be invisible in all three tiers.
        "tier": s.tier,
        # When a value written through the plugin takes effect, or "compose" for a
        # leaf the container cannot change (ADR-0044); the live `jsettings list`
        # row carries the same word beside the current value.
        "applies": applies(s),
    }
    if s.env:
        entry["env"] = s.env
    if s.hermes_key:
        entry["hermes_key"] = s.hermes_key
    if s.choices:
        entry["choices"] = list(s.choices)
    if s.min is not None:
        entry["min"] = s.min
    if s.max is not None:
        entry["max"] = s.max
    if s.shape:
        entry["shape"] = s.shape
    if not s.secret and s.default is not None:
        entry["default"] = s.default
    return entry


# --------------------------------------------------------------------------- #
# docs/reference/settings.md
# --------------------------------------------------------------------------- #
def render_settings_doc() -> str:
    """The settings reference — a table per group, in group order."""
    lines: list[str] = [
        "# Settings reference",
        "",
        f"<!-- {MARK} -->",
        "",
        "Every setting JARVIS reads is declared once in `aura-schema/` and this page is",
        "generated from it (`make schema`). A setting lands in one or more places: a `.env`",
        "variable (the deploy stack and the apps), a Hermes `config.yaml` key (the agent), or",
        "the runtime `jsettings` allow-list (changeable live from the console, the phone or the",
        "agent — the **Live** column). Secrets show their name and shape only; the value lives",
        "in `.env` and is never committed.",
        "",
        "Columns: **Env** the `.env` variable · **Hermes key** the `config.yaml` path · **Type** ·",
        "**Default** (blank for a secret) · **Restart** if a change needs one · **Live** if it is",
        "in the `jsettings` allow-list. A setting marked *(advanced)* is a fine-grained knob the",
        "settings screens fold away by default.",
        "",
        "The Hermes plugins and the adapter read these values as attributes of the validated",
        "`aura_schema.Settings` object (`from_env()`), never from the environment directly;",
        "the package must be installed in the Hermes venv (the image does this; on a source",
        "checkout: `~/.hermes/hermes-agent/venv/bin/pip install -e /opt/jarvis/aura-schema`).",
        "jarvis-core keeps its own Home-Assistant-shaped configuration and is outside this schema",
        "(V2_PLAN §3.3).",
        "",
    ]
    for group in Group:
        rows = [s for s in SETTINGS if s.group is group]
        if not rows:
            continue
        lines.append(f"## {group.value}")
        lines.append("")
        lines.append(GROUP_DESCRIPTIONS[group])
        lines.append("")
        lines.append("| Setting | Env | Hermes key | Type | Default | Secret | Restart | Live | Description |")
        lines.append("|---|---|---|---|---|:--:|:--:|:--:|---|")
        for s in rows:
            lines.append(
                "| `{key}` | {env} | {hkey} | {typ} | {default} | {secret} | {restart} | {live} | {desc} |".format(
                    key=s.key,
                    env=f"`{s.env}`" if s.env else "—",
                    hkey=f"`{s.hermes_key}`" if s.hermes_key else "—",
                    typ=_doc_type(s),
                    default=_doc_default(s),
                    secret="yes" if s.secret else "—",
                    restart="yes" if s.restart_needed else "—",
                    live="yes" if s.settable else "—",
                    desc=("*(advanced)* " if s.advanced else "") + s.description.replace("|", "\\|"),
                )
            )
        lines.append("")
    return "\n".join(lines)


def _doc_type(s: Setting) -> str:
    if s.choices:
        return "enum (" + " \\| ".join(s.choices) + ")"
    return s.kind.value


def _doc_default(s: Setting) -> str:
    if s.secret:
        return "—"
    if s.default is None:
        return "—"
    if s.default == "":
        return "*(empty)*"
    if isinstance(s.default, bool):
        return "`true`" if s.default else "`false`"
    if isinstance(s.default, list):
        return "`[]`" if not s.default else "`" + ", ".join(map(str, s.default)) + "`"
    if isinstance(s.default, dict):
        return "`{}`" if not s.default else "`" + json.dumps(s.default) + "`"
    return f"`{s.default}`"


# --------------------------------------------------------------------------- #
# write / check
# --------------------------------------------------------------------------- #
#: Each output: the destination path and the function that renders its content.
OUTPUTS: tuple[tuple[Path, Callable[[], str]], ...] = (
    (CONFIG_TEMPLATE, render_config_template),
    (CONTRACT, render_contract),
    (WEB_CONTRACT, render_contract),
    (SETTINGS_DOC, render_settings_doc),
)


def write_all() -> list[Path]:
    written: list[Path] = []
    for path, render in OUTPUTS:
        content = render()
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            written.append(path)
    return written


def check_all() -> list[Path]:
    """Paths whose on-disk content differs from what the schema would render."""
    stale: list[Path] = []
    for path, render in OUTPUTS:
        content = render()
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the settings-derived files.")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if any generated file is stale (write nothing)")
    args = parser.parse_args(argv)

    if args.check:
        stale = check_all()
        if stale:
            print("stale (run `make schema`):", file=sys.stderr)
            for p in stale:
                print(f"  {p.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("settings files are in sync")
        return 0

    written = write_all()
    if written:
        for p in written:
            print(f"wrote {p.relative_to(ROOT)}")
    else:
        print("settings files already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
