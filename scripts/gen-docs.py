def gen_paired_access() -> str:
    """What a paired device's token may reach, straight from the tables the doors read.

    Loaded by file path, not as ``aura.paired_access``: the house package is not
    installed in the docs job, and the module imports only ``typing``. The page says
    what the door lets through, not what a handler does behind it (see the module's
    docstring for the narrowing and for what the door does not cover).
    """
    spec = importlib.util.spec_from_file_location(
        "_paired_access", ROOT / "aura-core" / "aura" / "paired_access.py")
    assert spec and spec.loader
    pa = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pa)

    def table(head: str, rows: list[tuple[str, str]]) -> list[str]:
        out = [f"| {head} | Client that needs it |", "| --- | --- |"]
        out += [f"| {_md_escape(key)} | {_md_escape(who)} |" for key, who in rows]
        return out + [""]

    out = [BANNER, "", "# Paired-device access", "",
           "What a device's own token may reach once the pairing flow has minted it. A phone or",
           "desktop can be lost or rooted, so the token is **denied by default**: it may send the",
           "WebSocket commands, reach the REST routes and hear the event types below, and nothing",
           "else. Both auth doors read these tables (`WebSocketHandler._dispatch`,",
           "`rest.require_token`), so a route added tomorrow is refused until it is listed in",
           "`aura-core/aura/paired_access.py` on purpose. Anything off a table answers the same",
           f"fixed `{pa.REFUSED_CODE}` (\"{pa.REFUSED_MESSAGE}\").", "",
           "This is a door, not a sandbox: handlers narrow some allowed commands further, and a",
           "caller holding the house token (the Hermes plugins, the adapter's relays) is not a",
           "paired token and is not limited here. The runbook",
           "([connectors](../runbooks/connectors.md)) says what the door does not cover.", "",
           f"{len(pa.WS_COMMANDS)} WebSocket commands, {len(pa.REST_ROUTES)} REST routes, "
           f"{len(pa.WS_EVENTS)} event types.", "",
           "## WebSocket commands", ""]
    out += table("Command", [(f"`{k}`", v) for k, v in pa.WS_COMMANDS.items()])
    out += ["## REST routes", ""]
    out += table("Route", [(f"`{m} {p}`", v) for (m, p), v in pa.REST_ROUTES.items()])
    out += ["## Event types", "",
            "`subscribe_events` on a paired socket names exactly one of these: no missing type, no",
            "`*`, so the feed is not the whole bus.", ""]
    out += table("Event", [(f"`{k}`", v) for k, v in pa.WS_EVENTS.items()])
    out += ["## The approver switch", "",
            "`jarvis/approve` is on the list because the phone is the owner's approval surface, so a",
            "paired token may answer any held request and a stolen one can approve until it is",
            "revoked. The owner's `approver` switch on the token (owner-only, on for a new pairing)",
            "is the narrower remedy for a device that should never approve: with it off the token is",
            "refused `jarvis/approve` and is not sent these two events, read live on an open socket.",
            "", ", ".join(f"`{e}`" for e in sorted(pa.APPROVAL_EVENTS)), ""]
    return "\n".join(out)


