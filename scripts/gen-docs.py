#: The fallback, for a task that names no tools. Most do not — `needs` is a
#: dependency list, not a manifest — and answering "conversation" for a
#: `browser-action` task would be a map that does not answer the question it
#: exists to answer. The category is what the task was written to exercise.
_INTERFACE_BY_CATEGORY: dict[str, str] = {
    "web-research": "http",
    "browser-action": "browser",
    "homelab-ops": "http",
    "coding-selfext": "cli",
    "personal-data": "file",
    "proactive-scheduled": "http",
    "multimodal": "vision",
    "voice": "audio",
    "safety": "conversation",
    "intelligence": "conversation",
}


def _interface_of(task) -> str:
    """The interface class a task exercises.

    The tools it declares first, because that is evidence; the category second,
    because that is what the task was written for; `conversation` last, for the
    categories that really are a conversation — safety and reasoning are about
    what JARVIS says, not what it reaches.
    """
    needs = {str(n) for n in (getattr(task, "needs", None) or [])}
    hit = sorted({name for tool, name in _INTERFACE_BY_TOOL if tool in needs})
    if len(hit) == 1:
        return hit[0]
    if len(hit) > 1:
        return "mixed"
    return _INTERFACE_BY_CATEGORY.get(getattr(task, "category", ""), "conversation")


def _last_passed() -> dict[str, str]:
    """Task id -> the date of the newest run in which it passed.

    Read from `bench/results/**/*.json` rather than kept by hand: a date somebody
    types is a date that is right once. A task with no passing run anywhere is
    absent, and the row says so rather than showing a blank that reads as zero.
    """
    seen: dict[str, str] = {}
    for path in sorted((ROOT / "bench" / "results").rglob("*.json")):
        # The nightly canary's runs are gitignored host-local output: counting them would
        # make CAPABILITIES.md reproducible only on the production host and fail docs-check.
        if "canary" in path.parts:
            continue
        try:
            run = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        day = str(run.get("timestamp", ""))[:10]
        if not day:
            continue
        for record in run.get("records", []):
            if record.get("status") == "pass":
                rid = str(record.get("id", ""))
                if rid and day > seen.get(rid, ""):
                    seen[rid] = day
    return seen


