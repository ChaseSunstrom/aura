def gen_plugins(plugins: list[PluginInfo]) -> str:
    tpl = _template()
    enabled = set(tpl.get("plugins", {}).get("enabled", []))
    lines = [
        BANNER,
        "",
        "# Plugin reference",
        "",
        f"The {len(plugins)} in-repo Hermes plugins under `hermes/plugins/`. Each is loaded",
        "when its name is in `plugins.enabled` in `deploy/config.template.yaml`. Tools,",
        "commands and hooks below are read from each plugin's own `register()` call.",
        "",
        "| Plugin | Toolset | Enabled | Tools | Slash | Hooks |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for p in plugins:
        cmds = ", ".join(f"`/{c[0]}`" for c in p.commands) or "—"
        hooks = ", ".join(f"`{h}`" for h in sorted(set(p.hooks))) or "—"
        lines.append(
            f"| `{p.name}` | `{p.toolset}` | {'yes' if p.name in enabled else 'no'} "
            f"| {len(p.tools)} | {cmds} | {hooks} |"
        )
    lines.append("")
    for p in plugins:
        lines += [f"## `{p.name}`", ""]
        if p.summary:
            lines += [p.summary, ""]
        lines.append(f"- **Toolset:** `{p.toolset}`")
        lines.append(f"- **Enabled by default:** {'yes' if p.name in enabled else 'no'}")
        if p.tools:
            reqs = sorted({str(t[2]) for t in p.tools if t[2]})
            tools = ", ".join(f"`{t[0]}`" for t in p.tools)
            lines.append(f"- **Tools ({len(p.tools)}):** {tools}")
            if reqs:
                lines.append(f"- **Requires env:** {', '.join('`' + r + '`' for r in reqs)}")
        if p.commands:
            for name, desc, hint in p.commands:
                hint_s = f" `{hint}`" if hint else ""
                desc_s = f" — {desc}" if desc else ""
                lines.append(f"- **Command `/{name}`{hint_s}**{desc_s}")
        if p.hooks:
            lines.append(f"- **Hooks:** {', '.join('`' + h + '`' for h in sorted(set(p.hooks)))}")
        if p.image_gen:
            lines.append(f"- **Image-gen provider:** {', '.join('`' + g + '`' for g in p.image_gen)}")
        lines.append("")
    return "\n".join(lines)


SKILLS_DIR = ROOT / "hermes" / "skills"


def load_skills() -> list[tuple[str, str, str, str]]:
    """``(dir, name, description, version)`` for each ``hermes/skills/*/SKILL.md``.

    The frontmatter is the contract: Hermes builds the system prompt's skills index from
    ``name`` + ``description``, so a skill whose description does not say *when* to reach
    for it is invisible to the agent no matter how good the body is. A missing SKILL.md or
    a missing field is reported in the page rather than skipped, so the gap is visible.
    """
    out: list[tuple[str, str, str, str]] = []
    for d in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        md = d / "SKILL.md"
        if not md.is_file():
            out.append((d.name, "", "(no SKILL.md)", ""))
            continue
        text = md.read_text(encoding="utf-8")
        meta: dict = {}
        if text.startswith("---"):
            _, front, _ = text.split("---", 2)
            meta = yaml.safe_load(front) or {}
        out.append((d.name, str(meta.get("name") or ""), str(meta.get("description") or ""),
                    str(meta.get("version") or "")))
    return out


def gen_skills() -> str:
    skills = load_skills()
    lines = [
        BANNER,
        "",
        "# Skill reference",
        "",
        f"The {len(skills)} curated skills under `hermes/skills/`. The deploy image copies",
        "each one into `$HERMES_HOME/skills/` on every start (`deploy/entrypoint.sh`), so",
        "this list is what the deployed JARVIS can load. Hermes puts each skill's **name and",
        "description** in the system prompt and loads the body only when the agent calls",
        "`skill_view`, so the description is what decides whether a skill is ever used.",
        "",
        "| Skill | Version | When to use it |",
        "| --- | --- | --- |",
    ]
    for directory, name, description, version in skills:
        label = f"`{name}`" if name else f"`{directory}`"
        mismatch = " ⚠️ directory/name mismatch" if name and name != directory else ""
        lines.append(f"| {label} | {version or '—'} | {_md_escape(description)}{mismatch} |")
    lines.append("")
    return "\n".join(lines)


def gen_mcp() -> str:
    tpl = _template()
    servers = tpl.get("mcp_servers", {}) or {}
    lines = [
        BANNER,
        "",
        "# MCP server reference",
        "",
        "The Model Context Protocol servers Hermes launches, from the `mcp_servers` block",
        "of `deploy/config.template.yaml`. A server is off when its `enabled` renders",
        "false (the `gitlab` server is gated on `MCP_GITLAB_ENABLED`).",
        "",
        "| Server | Command | Enabled | Env |",
        "| --- | --- | --- | --- |",
    ]
    for name in sorted(servers):
        spec = servers[name] or {}
        cmd = spec.get("command", "")
        args = " ".join(str(a) for a in spec.get("args", []))
        full = _md_escape(f"`{cmd} {args}`".strip())
        raw = spec.get("enabled", True)
        if isinstance(raw, str):
            var = re.sub(r"[${}]", "", raw)
            en = f"gated on `{var}`" if var else "no"
        else:
            en = "yes" if raw else "no"
        env = ", ".join(f"`{k}`" for k in (spec.get("env") or {})) or "—"
        lines.append(f"| `{name}` | {full} | {en} | {env} |")
    return "\n".join(lines)


