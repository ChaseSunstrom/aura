_METHOD_RE = re.compile(
    r"export\s+(?:const|async\s+function|function)\s+(GET|POST|PUT|PATCH|DELETE)\b"
)
_DECO_RE = re.compile(r"@app\.(get|post|put|patch|delete|websocket|api_route)\(")


def _balanced(src: str, open_idx: int) -> str:
    """Return the text inside the ``(...)`` whose ``(`` is at ``open_idx``."""
    depth = 0
    for i in range(open_idx, len(src)):
        c = src[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return src[open_idx + 1:i]
    return src[open_idx + 1:]


def _adapter_routes(src: str) -> list[tuple[str, str, str]]:
    """(verb, path, auth) for each ``@app.*`` route, parsing one call at a time so a
    later ``methods=[...]`` cannot be swallowed across decorators."""
    out: list[tuple[str, str, str]] = []
    for m in _DECO_RE.finditer(src):
        deco = m.group(1)
        call = _balanced(src, m.end() - 1)
        pm = re.search(r"[\"']([^\"']+)[\"']", call)
        if not pm:
            continue
        path = pm.group(1)
        if deco == "websocket":
            verb = "WS"
        elif deco == "api_route":
            mm = re.search(r"methods\s*=\s*\[([^\]]*)\]", call)
            verb = ", ".join(x.strip().strip("\"'") for x in mm.group(1).split(",")) if mm else "ANY"
        else:
            verb = deco.upper()
        auth = "no" if path == "/health" else "yes"
        out.append((verb, path, auth))
    return out


def gen_api() -> str:
    lines = [
        BANNER,
        "",
        "# API endpoint reference",
        "",
        "Two HTTP surfaces sit on the LAN: the **adapter** (`jarvis-adapter`, the one",
        "origin the apps use, port 8643) and the **console** (`jarvis-web`, port 8199).",
        "The adapter proxies the Hermes API server (`/v1/*`, `/api/sessions*`,",
        "`/api/jobs*`) and Hermes serve (`/api/audio/*`) behind one bearer key, and relays",
        "the HUD and speak WebSockets. See the [HUD protocol](../hermes-hud-protocol.md).",
        "",
        "## Adapter (`aura-adapter/aura_adapter/app.py`)",
        "",
        "| Method | Path | Auth |",
        "| --- | --- | --- |",
    ]
    # Every route but /health takes Depends(require_key); the WS routes check the
    # bearer after accept (_accept_authed), so they are keyed too.
    src = (ROOT / "aura-adapter" / "aura_adapter" / "app.py").read_text()
    for verb, path, auth in _adapter_routes(src):
        lines.append(f"| {verb} | `{path}` | {auth} |")

    lines += [
        "",
        "## Console (`jarvis-web`, SvelteKit `+server.ts`)",
        "",
        "| Methods | Route |",
        "| --- | --- |",
    ]
    web_root = ROOT / "jarvis-web" / "src" / "routes"
    rows: list[tuple[str, str]] = []
    for f in web_root.rglob("+server.ts"):
        methods = sorted(set(_METHOD_RE.findall(f.read_text())))
        if not methods:
            continue
        rel = f.parent.relative_to(web_root).as_posix()
        route = "/" + rel if rel != "." else "/"
        rows.append((route, ", ".join(methods)))
    for route, methods in sorted(rows):
        lines.append(f"| {methods} | `{route}` |")
    return "\n".join(lines)


def gen_hud() -> str:
    contract = DOCS / "hermes-hud-protocol.md"
    methods: list[str] = []
    in_table = False
    for line in contract.read_text().splitlines():
        if line.startswith("### Methods the apps use"):
            in_table = True
            continue
        if in_table:
            if line.startswith("### ") or line.startswith("## "):
                break
            m = re.match(r"\|\s*`([^`]+)`\s*\|", line)
            if m and m.group(1) not in ("Method",):
                methods.append(m.group(1))
    lines = [
        BANNER,
        "",
        "# HUD protocol",
        "",
        "The apps talk to JARVIS over a JSON-RPC 2.0 WebSocket on the adapter. The full,",
        "authoritative contract — request/event frames, `command.dispatch` result types,",
        "panel kinds, the voice relay path — lives in",
        "[`docs/hermes-hud-protocol.md`](../hermes-hud-protocol.md), which the web and",
        "Android suites both pin against `tests/contracts/`.",
        "",
        "## Methods the apps call",
        "",
    ]
    if methods:
        for name in methods:
            lines.append(f"- `{name}`")
    else:
        lines.append("- see the contract doc")
    lines += [
        "",
        "See the contract doc for parameters, results and the events the HUD renders.",
    ]
    return "\n".join(lines)


