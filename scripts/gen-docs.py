"""Generate the ``docs/reference/*`` pages and ``CAPABILITIES.md`` from the repo.

Every page this writes carries a "GENERATED — do not edit" banner and is derived
only from files already in the tree (plus the plugins' own ``register()`` calls,
run against a recording stub). Nothing here calls the API server, starts a run, or
reaches the network, so ``make docs`` is reproducible in CI: the CI sync check runs
``make docs`` and fails if the working tree changed, which only happens when a source
the generator reads moved without the page being regenerated.

Sources, per page (the v2 plan §3.4):

* ``reference/tools.md``         — toolset enable/disable state from
  ``deploy/config.template.yaml`` + the in-repo plugin toolsets; toolset display
  names captured from ``hermes tools list --platform api_server`` on the pinned
  Hermes v0.21.0 build (D1), embedded below so generation needs no live CLI.
* ``reference/plugins.md``       — each ``hermes/plugins/<name>/`` imported with a
  recording ``ctx`` so the tool / command / hook lists are exactly what the plugin
  registers (loops and all), plus the module docstring's first line.
* ``reference/mcp-servers.md``   — the ``mcp_servers`` block of the config template.
* ``reference/slash-commands.md``— plugin ``register_command`` calls + the
  TUI-gateway ``command.dispatch`` commands documented in the HUD contract.
* ``reference/api-endpoints.md``  — the adapter's FastAPI routes + the console's
  SvelteKit ``+server.ts`` handlers, read from the code.
* ``reference/hud-protocol.md``   — a thin index that links the contract doc
  (``docs/hermes-hud-protocol.md``) and lists the methods it defines.
* ``reference/approval-matrix.md`` — the approval matrix, the egress allowlist and
  the sealed paths, read from ``hermes/plugins/_shared/_matrix.py`` itself. A
  hand-kept copy of a safety policy drifts invisibly: the page would still read
  correctly while describing rules the gate no longer applies.
* ``reference/paired-access.md`` — the WebSocket commands, REST routes and event types a
  paired device's token may reach, each with its client, read from
  ``aura-core/aura/paired_access.py`` (loaded by path; it imports only ``typing``).
* ``CAPABILITIES.md``            — one row per JCB task (``bench/tasks/**/*.yaml``),
  grouped by category: id, what it proves (the task prompt), checker type, flags.

``reference/settings.md`` is NOT written here: it is generated by the settings-schema
helper (``make schema``); this generator only links it.
"""

