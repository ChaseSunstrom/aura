# --------------------------------------------------------------------------- util
def _template() -> dict:
    return yaml.safe_load((ROOT / "deploy" / "config.template.yaml").read_text())


def _md_escape(text: str) -> str:
    """Keep a cell on one line and un-break the table."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _write(path: Path, body: str, results: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = body if body.endswith("\n") else body + "\n"
    old = path.read_text() if path.exists() else None
    path.write_text(text)
    rel = path.relative_to(ROOT)
    results.append(f"{'wrote' if old != text else 'ok   '} {rel}")


# ---------------------------------------------------------------- plugin introspection
class _RecordingCtx:
    """A stand-in for Hermes's plugin ``ctx`` that records what a plugin registers.

    The plugin's ``register(ctx)`` is pure wiring — it only calls these ``register_*``
    methods — so running it here yields the authoritative tool/command/hook list,
    including tools added in a loop that a regex over the source would miss.
    """

    def __init__(self) -> None:
        self.tools: list[tuple[str, str, object]] = []
        self.commands: list[tuple[str, str, str]] = []
        self.hooks: list[str] = []
        self.image_gen: list[str] = []

    def register_tool(self, name=None, toolset=None, schema=None, handler=None,
                      check_fn=None, requires_env=None, emoji=None, **_):
        self.tools.append((str(name), str(toolset), requires_env))

    def register_command(self, name, handler=None, description="", args_hint=""):
        self.commands.append((str(name), str(description), str(args_hint)))

    def register_hook(self, event, callback=None):
        self.hooks.append(str(event))

    def register_image_gen_provider(self, provider):
        self.image_gen.append(getattr(provider, "__name__", provider.__class__.__name__))

    def __getattr__(self, _name):  # tolerate any other ctx API a plugin may touch
        return lambda *a, **k: None


class PluginInfo:
    def __init__(self, name: str, summary: str, ctx: _RecordingCtx) -> None:
        self.name = name
        self.summary = summary
        self.tools = ctx.tools
        self.commands = ctx.commands
        self.hooks = ctx.hooks
        self.image_gen = ctx.image_gen

    @property
    def toolset(self) -> str:
        return self.tools[0][1] if self.tools else "—"


def load_plugins() -> list[PluginInfo]:
    plugins: list[PluginInfo] = []
    base = ROOT / "hermes" / "plugins"
    for d in sorted(base.iterdir()):
        if not d.is_dir() or d.name.startswith("_") or d.name == "__pycache__":
            continue
        init = d / "__init__.py"
        if not init.exists():
            continue
        pkgname = "jplug_" + d.name.replace("-", "_")
        spec = importlib.util.spec_from_file_location(
            pkgname, init, submodule_search_locations=[str(d)]
        )
        mod = importlib.util.module_from_spec(spec)
        sys.modules[pkgname] = mod
        spec.loader.exec_module(mod)
        ctx = _RecordingCtx()
        if hasattr(mod, "register"):
            mod.register(ctx)
        summary = (mod.__doc__ or "").strip().splitlines()[0] if mod.__doc__ else ""
        # trim "name — " prefix that many docstrings lead with
        summary = re.sub(rf"^{re.escape(d.name)}\s*[—-]\s*", "", summary).strip()
        plugins.append(PluginInfo(d.name, summary, ctx))
    return plugins


