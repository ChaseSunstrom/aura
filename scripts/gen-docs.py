def gen_capabilities_json() -> str:
    """The same map as data, for the HUD's capability panel.

    The console cannot usefully parse a markdown page, and a second hand-kept
    list would be a second thing to drift. One generator, two renderings: the
    page a person reads and the rows a panel draws.
    """
    from bench import CATEGORIES  # noqa: E402
    from bench.schema import load_all

    tasks = load_all(ROOT / "bench" / "tasks")
    passed = _last_passed()
    rows = [
        {
            "id": t.id,
            "category": t.category,
            "interface": _interface_of(t),
            "checker": t.checker_type,
            "proves": re.sub(r"\s+", " ", t.prompt).strip()[:200],
            "last_passed": passed.get(t.id, ""),
            "fast": bool(t.fast),
            "safety": t.safety_expectation,
        }
        for t in sorted(tasks, key=lambda t: (t.category, t.id))
    ]
    never = [r["id"] for r in rows if not r["last_passed"]]
    return json.dumps(
        {
            "_comment": ("The capability map as data — the same rows CAPABILITIES.md renders, for "
                         "the HUD's capability panel. Generated by scripts/gen-docs.py; a second "
                         "hand-kept list would be a second thing to drift."),
            "generated_from": "bench/tasks/**/*.yaml + bench/results/**/*.json",
            "categories": [c for c in CATEGORIES if any(r["category"] == c for r in rows)],
            "total": len(rows),
            "never_passed": len(never),
            "rows": rows,
        },
        indent=2,
        ensure_ascii=False,
    ) + "\n"


def gen_capabilities() -> str:
    from bench import CATEGORIES  # noqa: E402
    from bench.schema import load_all

    tasks = load_all(ROOT / "bench" / "tasks")
    passed = _last_passed()
    by_cat: dict[str, list] = {c: [] for c in CATEGORIES}
    for t in tasks:
        by_cat.setdefault(t.category, []).append(t)

    lines = [
        BANNER,
        "",
        "# CAPABILITIES",
        "",
        "Every capability JARVIS claims, mapped to the JARVIS Capability Benchmark (JCB)",
        f"task that proves it. Generated from `bench/tasks/**/*.yaml` ({len(tasks)} tasks",
        f"across {len([c for c in by_cat if by_cat[c]])} categories) by `scripts/gen-docs.py`",
        "(`make capabilities`).",
        "",
        "\"Proves\" is the task prompt — the exact instruction the assistant is scored on.",
        "\"Checker\" is how the result is judged (see the v2 plan §2.3); `judge` rows use the",
        "local model and are flagged. `fast` rows are in the `bench:fast` MR subset.",
        "**Interface** is how JARVIS reaches the thing — the claim in Part 3 is about reach, so",
        "the map says it. **Last passed** is the newest run in `bench/results/` that scored the",
        "task; a task with no passing run anywhere says `never`, which is a fact about this",
        "repository rather than a blank that reads as zero.",
        "",
        "| Category | Tasks |",
        "| --- | --- |",
    ]
    for cat in CATEGORIES:
        n = len(by_cat.get(cat, []))
        if n:
            lines.append(f"| {cat} | {n} |")
    lines.append("")

    for cat in CATEGORIES:
        items = sorted(by_cat.get(cat, []), key=lambda t: t.id)
        if not items:
            continue
        lines += [f"## {cat}", ""]
        for t in items:
            proves = _md_escape(re.sub(r"\s+", " ", t.prompt).strip())
            if len(proves) > 160:
                proves = proves[:157].rstrip() + "…"
            flags = []
            if t.fast:
                flags.append("fast")
            if t.is_judge:
                flags.append("judge")
            if t.safety_expectation != "comply":
                flags.append(t.safety_expectation)
            flag_s = f" · {', '.join(flags)}" if flags else ""
            when = passed.get(t.id, "never")
            lines.append(
                f"- **{t.id}** — {proves} · interface: `{_interface_of(t)}` · "
                f"checker: `{t.checker_type}` · last passed: {when}{flag_s}"
            )
        lines.append("")
    return "\n".join(lines)


